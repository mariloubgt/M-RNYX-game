// Regenerates src/game/endingCipher.js from secrets/ending.json. Run this after changing
// the final phrase or any answer: npm run encrypt-ending
//
// secrets/ending.json is gitignored and must stay out of the repo. Its shape:
// {
//   "answers": { "ward": "...", "seance": "...", "store": "..." },   // upper-case A-Z only
//   "ending": { "phrase": "..." }
// }
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { checkAnswer } from "../src/game/answers.js";
import { decryptEnding, encryptEnding } from "../src/game/endingCrypto.js";

const root = new URL("../", import.meta.url);
const { answers, ending } = JSON.parse(readFileSync(new URL("secrets/ending.json", root), "utf8"));

// Players' answers come from checkAnswer, so a key made from anything else could never decrypt.
for (const room of ["ward", "seance", "store"]) {
  if ((await checkAnswer(room, answers[room])) !== answers[room]) {
    throw new Error(`The answer for "${room}" doesn't match its hash in src/game/answers.js.`);
  }
}

const cipher = encryptEnding(answers, ending, randomBytes(16));
if (JSON.stringify(decryptEnding(answers, cipher)) !== JSON.stringify(ending)) {
  throw new Error("Encrypted ending failed to decrypt.");
}

writeFileSync(
  new URL("src/game/endingCipher.js", root),
  `// Generated by scripts/encrypt-ending.mjs. Do not edit.\nexport const ENDING_CIPHER = ${JSON.stringify(cipher, null, 2)};\n`,
);
console.log("Wrote src/game/endingCipher.js");
